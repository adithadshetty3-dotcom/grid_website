-- Provision a NEW PostgreSQL database with the Timeline schema expected by Flask Alembic 0005.
-- Do not run this against the active SQLite file or use it as a destructive data migration.
BEGIN;

CREATE TABLE IF NOT EXISTS alembic_version (
  version_num VARCHAR(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS timeline_admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash VARCHAR(256) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  session_version INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS timeline_admin_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash VARCHAR(64) NOT NULL UNIQUE,
  csrf_token VARCHAR(64) NOT NULL,
  admin_id INTEGER NOT NULL REFERENCES timeline_admins(id) ON DELETE CASCADE,
  session_version INTEGER NOT NULL DEFAULT 0,
  expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_timeline_admin_sessions_admin_id ON timeline_admin_sessions(admin_id);
CREATE INDEX IF NOT EXISTS ix_timeline_admin_sessions_expires_at ON timeline_admin_sessions(expires_at);

CREATE TABLE IF NOT EXISTS timeline_milestones (
  id VARCHAR(36) PRIMARY KEY,
  title VARCHAR(90) NOT NULL,
  category VARCHAR(24) NOT NULL CHECK (category IN ('Events', 'Workshops', 'Achievements', 'Projects', 'Community')),
  date VARCHAR(10) NOT NULL,
  time VARCHAR(5) NOT NULL DEFAULT '',
  location VARCHAR(100) NOT NULL DEFAULT '',
  summary VARCHAR(180) NOT NULL,
  description VARCHAR(6000) NOT NULL,
  source_id VARCHAR(255) UNIQUE,
  images JSONB NOT NULL DEFAULT '[]'::jsonb,
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  is_published BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_timeline_milestones_public_order ON timeline_milestones(is_published, sort_order, date, id);

CREATE TABLE IF NOT EXISTS timeline_images (
  id VARCHAR(36) PRIMARY KEY,
  storage_key VARCHAR(40) NOT NULL UNIQUE,
  original_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(32) NOT NULL,
  size_bytes INTEGER NOT NULL CHECK (size_bytes > 0),
  width INTEGER NOT NULL CHECK (width > 0),
  height INTEGER NOT NULL CHECK (height > 0),
  sha256 VARCHAR(64) NOT NULL,
  uploaded_by INTEGER NOT NULL REFERENCES timeline_admins(id) ON DELETE RESTRICT,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_timeline_images_uploaded_by ON timeline_images(uploaded_by);

CREATE TABLE IF NOT EXISTS timeline_site_settings (
  id VARCHAR(24) PRIMARY KEY,
  starfield_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO alembic_version(version_num)
SELECT '0005_timeline_starfield_setting'
WHERE NOT EXISTS (SELECT 1 FROM alembic_version);

COMMIT;
